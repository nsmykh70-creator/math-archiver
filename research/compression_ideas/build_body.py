class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            self.notify('TOCEntry', (level, text, self.page, key))


def add_heading(text, style, level=0):
    key = 'h_%s' % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def h1_rule():
    t = Table([['']], colWidths=[AVAIL_W], rowHeights=[2])
    t.setStyle(TableStyle([('BACKGROUND', (0, 0), (-1, -1), ACCENT),
                           ('TOPPADDING', (0, 0), (-1, -1), 0),
                           ('BOTTOMPADDING', (0, 0), (-1, -1), 0)]))
    return t


MAX_KEEP_HEIGHT = A4[1] * 0.4


def safe_keep_together(elements):
    total_h = 0
    for el in elements:
        w, h = el.wrap(AVAIL_W, PAGE_H)
        total_h += h
    if total_h <= MAX_KEEP_HEIGHT:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)


def chapter(story, num, title, first_para_text):
    """H1 + акцентная линия + первый абзац, с защитой от «висячих» заголовков."""
    story.append(CondPageBreak(H1_THRESHOLD))
    head = add_heading(f'{num}. {title}', h1, level=0)
    rule = h1_rule()
    first = Paragraph(first_para_text, body)
    story.extend(safe_keep_together([head, rule, Spacer(1, 8), first]))


def sub(story, title, first_para_text=None):
    head = add_heading(title, h2, level=1)
    if first_para_text:
        story.extend(safe_keep_together([head, Paragraph(first_para_text, body)]))
    else:
        story.append(head)


def fit_image(img_path, max_w, max_h):
    img = PILImage.open(img_path)
    ow, oh = img.size
    ratio = min(max_w / ow if ow > max_w else 1.0, max_h / oh if oh > max_h else 1.0)
    return Image(img_path, width=ow * ratio, height=oh * ratio)


def add_chart(story, filename, caption_text):
    img = fit_image(os.path.join(CHARTS, filename), AVAIL_W, A4[1] * 0.35)
    story.append(Spacer(1, 16))
    story.extend(safe_keep_together([img, Spacer(1, 6), Paragraph(caption_text, caption)]))
    story.append(Spacer(1, 14))


def make_table(header, rows, ratios, align_center_cols=()):
    col_w = [r * AVAIL_W * 0.98 for r in ratios]
    data = [[Paragraph(f'<b>{c}</b>', tbl_hdr) for c in header]]
    for row in rows:
        cells = []
        for i, c in enumerate(row):
            st = tbl_cell_c if i in align_center_cols else tbl_cell
            cells.append(Paragraph(str(c), st))
        data.append(cells)
    t = Table(data, colWidths=col_w, hAlign='CENTER', repeatRows=1)
    style = [('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
             ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
             ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
             ('LEFTPADDING', (0, 0), (-1, -1), 6),
             ('RIGHTPADDING', (0, 0), (-1, -1), 6),
             ('TOPPADDING', (0, 0), (-1, -1), 5),
             ('BOTTOMPADDING', (0, 0), (-1, -1), 5)]
    for i in range(1, len(data)):
        style.append(('BACKGROUND', (0, i), (-1, i),
                      TABLE_ROW_ODD if i % 2 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    return t


def add_table(story, header, rows, ratios, caption_text, align_center_cols=()):
    t = make_table(header, rows, ratios, align_center_cols)
    story.append(Spacer(1, 14))
    if len(rows) <= 15:
        story.extend(safe_keep_together([t, Spacer(1, 5), Paragraph(caption_text, caption)]))
    else:
        story.append(t)
        story.append(Spacer(1, 5))
        story.append(Paragraph(caption_text, caption))
    story.append(Spacer(1, 12))


def stat_row(story, stats):
    """Три метрики в ряд: значение + подпись."""
    cells = []
    for val, lbl in stats:
        inner = Table([[Paragraph(f'<b>{val}</b>', stat_big)],
                       [Paragraph(lbl, stat_lbl)]],
                      colWidths=[AVAIL_W / 3 - 14])
        inner.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
            ('BOX', (0, 0), (-1, -1), 1, ACCENT),
            ('TOPPADDING', (0, 0), (-1, 0), 9),
            ('BOTTOMPADDING', (0, 1), (-1, 1), 9),
            ('TOPPADDING', (0, 1), (-1, 1), 2),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE')]))
        cells.append(inner)
    wrap = Table([cells], colWidths=[AVAIL_W / 3] * 3, hAlign='CENTER')
    wrap.setStyle(TableStyle([('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
                              ('LEFTPADDING', (0, 0), (-1, -1), 4),
                              ('RIGHTPADDING', (0, 0), (-1, -1), 4)]))
    story.append(Spacer(1, 10))
    story.append(KeepTogether(wrap))
    story.append(Spacer(1, 12))


